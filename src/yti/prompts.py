def gaps_user_prompt(videos: list[dict]) -> str:
    lines = []
    for v in videos:
        title = (v.get("title") or "").strip()
        desc = (v.get("description") or "").strip().replace("\n", " ")
        if len(desc) > 240:
            desc = desc[:240] + "…"
        lines.append(f"- {title} :: {desc}")
    body = "\n".join(lines) if lines else "(нет видео)"
    return (
        "Видео на канале:\n\n"
        f"{body}\n\n"
        "Выдай:\n"
        "1) Кластеры тем с указанием, какие ролики туда попадают.\n"
        "2) Темы, раскрытые обильно (топ-3) — с оценкой почему это уже хорошо закрыто.\n"
        "3) Темы, которые упоминаются вскользь / отсутствуют.\n"
        "4) 5–7 конкретных идей роликов, закрывающих пробелы (с короткой логикой)."
    )
