def ask_user_prompt(question: str, hits: list[dict]) -> str:
    return (
        f"Вопрос: {question}\n\n"
        f"Фрагменты транскриптов:\n\n{format_hits_for_prompt(hits)}\n\n"
        "Сформулируй ответ строго по фрагментам, со ссылками на источники."
    )


