"""Prompt templates for the high-level commands."""
from __future__ import annotations

from .search import fmt_timestamp, with_timestamp_url


def format_hits_for_prompt(hits: list[dict]) -> str:
    """Render hits as numbered citations the LLM can refer to as [1], [2]…"""
    blocks: list[str] = []
    for i, h in enumerate(hits, start=1):
        ts = fmt_timestamp(h["ts_start"])
        url = with_timestamp_url(h)
        blocks.append(
            f"[{i}] «{h['title']}» @ {ts} ({url})\n"
            f"    {h['text']}"
        )
    return "\n\n".join(blocks)


